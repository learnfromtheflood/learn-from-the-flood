async function registerServiceWorker() {
  if (!('serviceWorker' in navigator)) { offlineStatus.textContent = 'Offline mode is not supported in this browser'; downloadBtn.disabled = true; return; }
  try { await navigator.serviceWorker.register('service-worker.js'); await navigator.serviceWorker.ready; checkOfflineStatus(); }
  catch (err) { console.error(err); offlineStatus.textContent = 'Could not enable offline mode'; }
}

async function checkOfflineStatus() {
  if (!('caches' in window)) return;
  const audioCache = await caches.open(AUDIO_CACHE);
  let foundAudio = 0;
  for (const track of tracks) if (await audioCache.match(new URL(track.file, document.baseURI).href)) foundAudio++;
  const allImages = tracks.flatMap(t => t.images || []).map(url => new URL(url, document.baseURI).href);
  const imageCache = await caches.open(IMAGE_CACHE);
  let foundImages = 0;
  for (const url of allImages) if (await imageCache.match(url)) foundImages++;
  if (foundAudio === tracks.length && foundImages === allImages.length) {
    offlineStatus.textContent = 'Full tour audio + Section 1 images are ready offline';
    downloadBtn.textContent = 'Downloaded ✓';
  } else if (foundAudio > 0 || foundImages > 0) {
    offlineStatus.textContent = `${foundAudio}/${tracks.length} audio tracks and ${foundImages}/${allImages.length} images saved`;
  }
}

downloadBtn.addEventListener('click', async () => {
  if (!('caches' in window)) return;
  downloadBtn.disabled = true;
  progressWrap.classList.remove('hidden');
  progressWrap.setAttribute('aria-hidden', 'false');
  const allImages = tracks.flatMap(t => t.images || []).map(url => new URL(url, document.baseURI).href);
  const total = tracks.length + allImages.length;
  progressBar.max = total;
  progressBar.value = 0;
  let done = 0;
  try {
    const audioCache = await caches.open(AUDIO_CACHE);
    for (const track of tracks) {
      const url = new URL(track.file, document.baseURI).href;
      if (!(await audioCache.match(url))) {
        const response = await fetch(url, { cache: 'no-store' });
        if (!response.ok) throw new Error(`Could not download ${track.title}`);
        await audioCache.put(url, response.clone());
      }
      done++; progressBar.value = done; progressText.textContent = `${done} of ${total} items saved`;
    }
    const imageCache = await caches.open(IMAGE_CACHE);
    for (const url of allImages) {
      if (!(await imageCache.match(url))) {
        const response = await fetch(url, { cache: 'no-store' });
        if (!response.ok) throw new Error(`Could not download image ${url}`);
        await imageCache.put(url, response.clone());
      }
      done++; progressBar.value = done; progressText.textContent = `${done} of ${total} items saved`;
    }
    offlineStatus.textContent = 'Full tour audio + Section 1 images are ready offline';
    downloadBtn.textContent = 'Downloaded ✓';
    progressText.textContent = 'Offline download complete';
  } catch (err) {
    console.error(err);
    offlineStatus.textContent = 'Download interrupted — tap again when online';
    progressText.textContent = 'Download stopped before completion';
    downloadBtn.textContent = 'Resume offline download';
  } finally { downloadBtn.disabled = false; }
});

